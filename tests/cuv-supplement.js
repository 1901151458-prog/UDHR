const toSim = s => s.split('').map(c => T2S[c] || c).join('');

const TARGETS = [
  {book:1, ch:2,  v:2,  label:'创世记 2:2'},
  {book:2, ch:23, v:2,  label:'出埃及记 23:2'},
  {book:2, ch:18, v:21, label:'出埃及记 18:21'},
  {book:2, ch:31, v:2,  label:'出埃及记 31:2'},
  {book:2, ch:31, v:3,  label:'出埃及记 31:3'},
  {book:5, ch:15, v:7,  label:'申命记 15:7（复核）'}
];

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function getChapter(book, ch, tries) {
  for (let i = 1; i <= tries; i++) {
    const ctl = new AbortController();
    const to = setTimeout(() => ctl.abort(), 20000);
    try {
      const r = await fetch(`https://bolls.life/get-chapter/CUV/${book}/${ch}/`, {
        signal: ctl.signal, headers: { 'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)' }
      });
      if (r.status !== 200) throw new Error('HTTP ' + r.status);
      const j = await r.json();
      clearTimeout(to);
      return j;
    } catch (e) {
      clearTimeout(to);
      if (i < tries) { await sleep(1200 * i); continue; }
      throw e;
    }
  }
}

(async () => {
  const results = [];
  const chapterCache = {};
  for (const t of TARGETS) {
    const key = t.book + ':' + t.ch;
    try {
      if (!chapterCache[key]) {
        chapterCache[key] = await getChapter(t.book, t.ch, 4);
      }
      const chap = chapterCache[key];
      const arr = Array.isArray(chap) ? chap : (chap.chapter || []);
      const item = arr.find(x => Number(x.verse || x.v) === t.v);
      if (!item) {
        results.push({ label: t.label, ok: false, note: '该章取到 ' + arr.length + ' 节，但无第 ' + t.v + ' 节', raw: null });
        continue;
      }
      const trad = String(item.text || item.t || '').replace(/<[^>]+>/g, '').replace(/\s+/g, '');
      results.push({ label: t.label, ok: true, trad, sim: toSim(trad) });
    } catch (e) {
      results.push({ label: t.label, ok: false, note: '获取失败: ' + e.message, raw: null });
    }
    await sleep(400);
  }

  const lines = [];
  console.log('════ 任务一：和合本补测结果 ════');
  for (const r of results) {
    if (r.ok) {
      console.log('\n[' + r.label + ']  实测成功');
      console.log('  传统(API原文): ' + r.trad);
      console.log('  简体(转换)  : ' + r.sim);
      lines.push(r.label + '  ' + r.trad + '  ‖sim: ' + r.sim);
    } else {
      console.log('\n[' + r.label + ']  失败 - ' + r.note);
      lines.push(r.label + '  [获取失败: ' + r.note + ']');
    }
  }

  const fs = require('fs');
  fs.writeFileSync(process.argv[2] + '\\cuv-verses-supplement.txt', lines.join('\n'), 'utf8');
  fs.writeFileSync(process.argv[2] + '\\cuv-supplement.json', JSON.stringify(results, null, 2), 'utf8');
  console.log('\n已写入 tests/cuv-verses-supplement.txt 与 tests/cuv-supplement.json');
})().catch(e => { console.log('脚本级错误: ' + e.message); process.exit(1); });
